local C = Color3.fromRGB
local M = Enum.Material
local BALL = Enum.PartType.Ball
local BLACK = C(30, 25, 25)

local function v(x, y, z)
	return Vector3.new(x, y, z)
end
local function eyes(y, z, spread, size, color)
	return { { v(size, size, 0.05), v(-spread, y, z), color or BLACK }, { v(size, size, 0.05), v(spread, y, z), color or BLACK } }
end
local function legs(size, x, y, z, color)
	local list = {}
	for _, sx in { -x, x } do
		for _, sz in { -z, z } do
			table.insert(list, { size, v(sx, y, sz), color })
		end
	end
	return list
end
local function join(...)
	local all = {}
	for _, list in { ... } do
		for _, part in list do
			table.insert(all, part)
		end
	end
	return all
end

